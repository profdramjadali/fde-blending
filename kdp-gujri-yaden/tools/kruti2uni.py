MATRAS = "ािीुूृेैोौंःँॅ"
def convert(s):
    # Word smart quotes inside Kruti text are really ' and "
    s = s.replace("‘","'").replace("’","'").replace("“",'"').replace("”",'"')
    # ि (f) : move after next consonant cluster
    s = s.replace("±","Zं")
    for k,u in zip(K,U):
        s = s.replace(k,u)
    # i-matra reorder: f + consonant(+्+consonant)*
    s = re.sub(r"f((?:[क-ह]़?्)*[क-ह]़?)", r"\1ि", s)
    s = s.replace("f","ि")
    # reph Z: move before the syllable it follows
    s = re.sub(r"((?:[क-ह]़?्)*[क-ह]़?[ािीुूृेैोौंःँ]*)Z", r"र्\1", s)
    # fix vowel sign order like  ्ंा etc
    s = s.replace("ंा","ां").replace("ंे","ें").replace("ंै","ैं").replace("ंो","ों").replace("ंौ","ौं").replace("ंी","ीं")
    s = s.replace("अा","आ").replace("आै","औ").replace("आे","ओ").replace("एे","ऐ")
    s = s.replace("्ा","").replace("ाे","ो").replace("ाै","ौ")
    return s
